-- WorkSpot: structured weekly hours (generated from src/data/hours.json).
-- weekday: 0=Sunday..6=Saturday (JS Date.getDay); times are minutes since midnight.
-- Run in the Supabase dashboard SQL editor after 0001.
create table if not exists cafe_hours (
  cafe_id text not null references cafes(id),
  weekday smallint not null check (weekday between 0 and 6),
  opens_min smallint not null check (opens_min >= 0 and opens_min < 1440),
  closes_min smallint not null check (closes_min > 0 and closes_min <= 1440),
  primary key (cafe_id, weekday, opens_min)
);

alter table cafe_hours enable row level security;

drop policy if exists "public read" on cafe_hours;
create policy "public read" on cafe_hours for select using (true);

